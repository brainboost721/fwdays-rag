def build(doc_spec: list[tuple[str, str]], out_path: Path) -> None:
    styles = getSampleStyleSheet()
    title = ParagraphStyle("t", parent=styles["Title"], fontName=FONT_NAME, fontSize=14, leading=18)
    center = ParagraphStyle("c", parent=styles["Normal"], fontName=FONT_NAME, fontSize=10,
                            leading=14, alignment=TA_CENTER, spaceAfter=10)
    head2 = ParagraphStyle("h2", parent=styles["Heading2"], fontName=FONT_NAME, fontSize=11,
                           leading=15, spaceBefore=10, spaceAfter=4)
    body = ParagraphStyle("p", parent=styles["Normal"], fontName=FONT_NAME, fontSize=10,
                          leading=14, spaceAfter=6)
    kinds = {"h": title, "c": center, "h2": head2, "p": body}

    # invariant drops the build timestamp, so regenerating gives byte-identical files.
    doc = SimpleDocTemplate(
        str(out_path), pagesize=A4, invariant=1,
        leftMargin=22 * mm, rightMargin=22 * mm, topMargin=20 * mm, bottomMargin=20 * mm,
    )
    flow = []
    for kind, text in doc_spec:
        flow.append(Paragraph(text, kinds[kind]))
        if kind == "h":
            flow.append(Spacer(1, 4))
    doc.build(flow)


def main() -> None:
    if not FONT_PATH.is_file():
        raise SystemExit(f"Не знайдено шрифт з кирилицею: {FONT_PATH}")
    pdfmetrics.registerFont(TTFont(FONT_NAME, str(FONT_PATH)))
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for spec, name in [(CLOUDHUB, "dogovir_cloudhub.pdf"), (DESKLY, "dogovir_deskly.pdf")]:
        path = OUT_DIR / name
        build(spec, path)
        print(f"  {path.relative_to(OUT_DIR.parent.parent)}  ({path.stat().st_size // 1024} КБ)")


if __name__ == "__main__":
    main()
